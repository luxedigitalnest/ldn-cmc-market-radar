"""Create a genuine, reproducible browser-capture demonstration of this project's verified code and historical dashboard.
No fabricated price feeds, personal account screens or investment advice.
"""
from pathlib import Path
import html, shutil, subprocess, time
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "media"
OUT.mkdir(exist_ok=True)
def run(args):
    return subprocess.run(args, cwd=ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, check=True).stdout

tests = run(["python", "-m", "unittest", "discover", "-s", "tests", "-v"])
demo = run(["python", "cmc_market_radar.py", "--from-json", "examples/live_10_coinmarketcap_2026-11-20.json", "--out", str(OUT/"verified_replay.html")])
print(demo.strip())
print("TEST RESULT:", tests.splitlines()[-1])
(ROOT / "media" / "verified_test_log.txt").write_text(tests + "\n" + demo, encoding="utf-8")

code = (ROOT / "cmc_market_radar.py").read_text(encoding="utf-8")
endpoint = next((line.strip() for line in code.splitlines() if "pro-api.coinmarketcap.com/public-api/v3/cryptocurrency/listings/latest" in line), "See source README")
head = """<html><meta charset='UTF-8'><style>body{margin:0;background:#0b1220;color:#e5efff;font-family:Consolas,monospace;padding:42px}h1{font-family:Segoe UI;font-size:34px;color:#93c5fd}h2{font:22px Segoe UI;color:#6ee7b7}p{font:17px Segoe UI;color:#cbd5e1}pre{white-space:pre-wrap;background:#111f36;border:1px solid #344765;border-radius:12px;padding:24px;font:15px/1.54 Consolas}strong{color:#fbbf24}</style>"""
proof = head + "<h1>Actual CLI execution · verified evidence</h1><p>This output was generated by running the source code on November 21, 2026. The source prices remain a recorded November 20, 2026 CMC API sample.</p>" + "<h2>Python test suite · genuine stdout</h2><pre>"+html.escape(tests)+"</pre><h2>Reproducible offline replay · genuine stdout</h2><pre>"+html.escape(demo)+"</pre><h2>Exact source endpoint</h2><pre>"+html.escape(endpoint)+"</pre><p><strong>Read-only historical demonstration. Not financial advice.</strong></p></html>"
(OUT / "verified_execution.html").write_text(proof, encoding="utf-8")

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    ctx = browser.new_context(viewport={"width":1280,"height":720}, device_scale_factor=1, record_video_dir=str(OUT / "raw"), record_video_size={"width":1280,"height":720})
    page = ctx.new_page()
    page.goto((OUT / "verified_replay.html").as_uri(), wait_until="load")
    page.wait_for_timeout(1800)
    page.screenshot(path=str(OUT/"actual_dashboard.png"))
    # This is actual scrolling of the real rendered dashboard, not generated UI artwork.
    for y,hold in [(0,4),(420,6),(960,7),(1500,6),(0,6)]:
        page.evaluate("(y) => window.scrollTo({top:y,behavior:'smooth'})", y)
        page.wait_for_timeout(900)
        time.sleep(hold)
    page.goto((OUT / "verified_execution.html").as_uri(), wait_until="load")
    for y,hold in [(0,5),(390,7),(950,6)]:
        page.evaluate("(y) => window.scrollTo({top:y,behavior:'smooth'})",y)
        page.wait_for_timeout(700)
        time.sleep(hold)
    # Capture repository documentation locally with contents accurately reconstructed from source files.
    md = (ROOT/"README.md").read_text(encoding="utf-8")
    docs = head + "<h1>Source code and reproducibility</h1><p>Public: github.com/luxedigitalnest/ldn-cmc-market-radar</p><pre>"+html.escape("\n".join(md.splitlines()[:48]))+"</pre><p>Historical snapshot is clearly dated. The CLI provides the current-data path when a network is available.</p></html>"
    (OUT/"verified_docs.html").write_text(docs,encoding="utf-8")
    page.goto((OUT/"verified_docs.html").as_uri(),wait_until="load")
    page.wait_for_timeout(5000)
    time.sleep(3)
    page.close()
    ctx.close()
    browser.close()
print("Raw videos:", list((OUT/"raw").glob("*.webm")))
